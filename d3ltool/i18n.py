def set_language(lang: str) -> None:
    if lang in STRINGS:
        _current["lang"] = lang


def get_language() -> str:
    return _current["lang"]


def tr(key: str, **kw) -> str:
    text = STRINGS.get(_current["lang"], {}).get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kw:
        try:
            text = text.format(**kw)
        except (KeyError, IndexError, ValueError):
            pass
    return text
